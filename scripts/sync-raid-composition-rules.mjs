import assert from "node:assert/strict";
import console from "node:console";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const { values } = parseArgs({
  options: { "discord-root": { type: "string" }, check: { type: "boolean", default: false } },
});
assert(values["discord-root"], "Pass --discord-root=/absolute/path/to/discord-website");
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const target = resolve(values["discord-root"]);
const project = JSON.parse(await readFile(join(target, "package.json"), "utf8"));
assert.equal(
  project.name,
  "forever-community-hub",
  "Expected the existing Discord website project",
);
const bytes = await readFile(join(root, "apps/web/src/lib/data/forever-raid-support.v1.json"));
const registry = JSON.parse(bytes.toString("utf8"));
assert.equal(registry.schema, "kfc-forever-raid-support.v1");
assert(/^forever-[a-z0-9.-]+$/.test(registry.revision));
assert(Array.isArray(registry.effects) && registry.effects.length > 0);
const hash = createHash("sha256").update(bytes).digest("hex");
const generated = `// Generated by wow-trader/scripts/sync-raid-composition-rules.mjs. Edit the shared JSON source.\nimport type { CompositionEffectRule } from "./composition";\n\nexport const foreverCompositionRevision = ${JSON.stringify(registry.revision)};\nexport const foreverCompositionSourceSha256 = ${JSON.stringify(hash)};\nexport const foreverCompositionRules = ${JSON.stringify(registry.effects, null, 2)} as const satisfies readonly CompositionEffectRule[];\n`;
const path = join(target, "lib/raids/forever-composition-rules.ts");
if (values.check)
  assert.equal(
    await readFile(path, "utf8"),
    generated,
    "Refresh the Discord projection from the shared registry",
  );
else await writeFile(path, generated);
console.log(
  JSON.stringify({
    status: values.check ? "verified" : "synchronized",
    revision: registry.revision,
    sha256: hash,
  }),
);
