local Addon = {}
assert(loadfile("apps/addon/WowTraderCollector/NativePendingRows.lua"))("WowTraderCollector", Addon)
local Pending = Addon.NativePendingRows
local state = Pending.New()
Pending.Track(state, 0, 100)
Pending.Track(state, 1, 100)
Pending.Track(state, 0, 100)
Pending.Track(state, 2)
assert(state.count == 3 and state.groupCounts[100] == 2, "Tracking deduplicates positions, including index zero")
Pending.Prioritize(state, 100)
Pending.Prioritize(state, 100, true)
assert(#state.ready == 1, "Duplicate notifications share one group queue entry")
local index = Pending.TakeReady(state)
assert(index == 0)
Pending.Complete(state, index)
Pending.Complete(state, index)
assert(state.count == 2 and state.groupCounts[100] == 1, "A row can only be completed once")
index = Pending.TakeReady(state)
assert(index == 1)
Pending.TakeReady(state)
Pending.Prioritize(state, 100)
assert(not Pending.HasReady(state), "Repeated observations cannot endlessly retry an unchanged group")
Pending.Prioritize(state, 100, true)
assert(Pending.TakeReady(state) == 1, "A new load completion can retry a still-pending row")
Pending.Complete(state, 1)
Pending.Track(state, 2, 200)
Pending.Track(state, 2, 201)
assert(state.groupCounts[200] == 0 and state.groupCounts[201] == 1, "A newly readable identity moves its group membership")
Pending.Prioritize(state, 201)
assert(Pending.TakeReady(state) == 2)
Pending.Complete(state, 2)
assert(state.count == 0)
Pending.Track(state, 0, 200)
assert(state.count == 0 and Pending.IsComplete(state, 0), "Consumed row positions never become pending again")

state = Pending.New()
for i = 0, 999 do Pending.Track(state, i, 100); Pending.Complete(state, i) end
Pending.Track(state, 1000, 100)
Pending.Prioritize(state, 100)
local row, checked = Pending.TakeReady(state, 25)
assert(row == nil and checked == 25 and Pending.HasReady(state), "Skipping old group members is frame-budgeted")
local total = checked
repeat row, checked = Pending.TakeReady(state, 25); total = total + checked until row ~= nil
assert(row == 1000 and total == 1001)
Pending.Complete(state, row)
Pending.TakeReady(state)
assert(not Pending.HasReady(state) and #state.ready == 0, "Consumed notification entries are released")
print("Pending-row grouping, notification deduplication, rescheduling, identity changes and skip budgets passed")
