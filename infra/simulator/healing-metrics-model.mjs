import assert from "node:assert/strict";

export const healingMetricsContract = Object.freeze({
  schema: "kfc-healing-metrics-contract.v1",
  hps: "effective-healing-plus-consumed-absorption",
  rawHealingIncludesOverhealing: true,
  shieldsRequireActualDamageAbsorption: true,
  untrackedHealthReceivesEffectiveCredit: false,
  ordinaryHealingResurrectsTargets: false,
  ownedPetHealingRollsUpToOwner: true,
  externalHealthGainsCreditTheHealer: false,
  classMechanicsAdmission: false,
});

const distributions = [
  ["rawHealing", "RawHealingHps", "raw_healing_hps"],
  ["effectiveHealing", "EffectiveHealingHps", "effective_healing_hps"],
  ["overhealing", "OverhealingHps", "overhealing_hps"],
  ["absorbedShielding", "AbsorbedHps", "absorbed_hps"],
];

function replace(source, before, after, count = 1) {
  const parts = source.split(before);
  assert.equal(parts.length - 1, count, "Healing model source anchor changed: " + before);
  return parts.join(after);
}

function protoMessage(source, name, transform) {
  const start = source.indexOf("message " + name + " {"),
    end = source.indexOf("\n}", start);
  assert(start >= 0 && end > start, "Missing protocol message: " + name);
  return source.slice(0, start) + transform(source.slice(start, end)) + source.slice(end);
}

/** Render an isolated metrics overlay; inputs must be the exact captured engine sources. No active source files are written.
 * @param {{api: string, delivery: string, metrics: string, raid: string, concurrent: string}} source
 * @returns {{api: string, delivery: string, metrics: string, raid: string, concurrent: string}}
 */
export function renderHealingMetricsSources(source) {
  let api = protoMessage(source.api, "TargetedActionMetrics", (body) =>
    replace(
      body,
      "\tdouble healing = 11;",
      `\tdouble healing = 11;
  // Actual health restored, excluding overhealing and shield capacity.
  double effective_healing = 39;
  double overhealing = 40;
  double effective_crit_healing = 41;`,
    ),
  );
  for (const [name, first] of [
    ["UnitMetrics", 18],
    ["PartyMetrics", 4],
    ["RaidMetrics", 4],
  ])
    api = protoMessage(
      api,
      name,
      (body) =>
        body +
        "\n" +
        distributions
          .map(([, , field], index) => `  DistributionMetrics ${field} = ${first + index};`)
          .join("\n"),
    );

  let delivery = replace(source.delivery, '\t"fmt"', '\t"fmt"\n\t"math"');
  delivery = replace(
    delivery,
    "\tThreat         float64 // The amount of threat generated by this cast.",
    `\tThreat         float64 // The amount of threat generated by this cast.
  EffectiveHealing float64 // Actual health restored by this heal.
  Overhealing float64 // Raw healing that restored no health.`,
  );
  delivery = replace(
    delivery,
    "\tresult.AbsorbedDamage = 0",
    "\tresult.AbsorbedDamage = 0\n\tresult.EffectiveHealing = 0\n\tresult.Overhealing = 0",
  );
  delivery = replace(
    delivery,
    `func (spell *Spell) dealHealingInternal(sim *Simulation, isPeriodic bool, result *SpellResult) {
\tif result.DidCrit() {
\t\tspell.SpellMetrics[result.Target.UnitIndex].TotalCritHealing += result.Damage
\t}
\tspell.SpellMetrics[result.Target.UnitIndex].TotalHealing += result.Damage
\tspell.SpellMetrics[result.Target.UnitIndex].TotalThreat += result.Threat
\tif result.Target.HasHealthBar() {
\t\tresult.Target.GainHealth(sim, result.Damage, spell.HealthMetrics(result.Target))
\t}`,
    `func (spell *Spell) dealHealingInternal(sim *Simulation, isPeriodic bool, result *SpellResult) {
  if result.Damage < 0 || math.IsNaN(result.Damage) || math.IsInf(result.Damage, 0) {
    panic("Invalid raw healing amount")
  }
  // Ordinary healing cannot bring a dead target back to life.
  if result.Target.HasHealthBar() && result.Target.CurrentHealth() <= 0 {
    spell.DisposeResult(result)
    return
  }
  effective := 0.0
  if result.Target.HasHealthBar() {
    before := result.Target.CurrentHealth()
    result.Target.GainHealth(sim, result.Damage, spell.HealthMetrics(result.Target))
    effective = result.Target.CurrentHealth() - before
  }
  result.EffectiveHealing = effective
  result.Overhealing = result.Damage - effective
  metrics := &spell.SpellMetrics[result.Target.UnitIndex]
  metrics.TotalHealing += result.Damage
  metrics.TotalEffectiveHealing += effective
  metrics.TotalOverhealing += result.Overhealing
  metrics.TotalThreat += result.Threat
  if result.DidCrit() {
    metrics.TotalCritHealing += result.Damage
    metrics.TotalEffectiveCritHealing += effective
  }`,
  );

  let metrics = replace(
    source.metrics,
    "\thps    DistributionMetrics",
    "\thps    DistributionMetrics\n" +
      distributions.map(([name]) => `  ${name} DistributionMetrics`).join("\n"),
  );
  metrics = replace(
    metrics,
    "\tTotalHealing                float64 // Healing done by all casts of this spell.",
    `\tTotalHealing                float64 // Raw healing, including overhealing.
  TotalEffectiveHealing float64
  TotalOverhealing float64
  TotalEffectiveCritHealing float64`,
  );
  metrics = replace(
    metrics,
    "\tHealing                float64",
    "\tHealing                float64\n  EffectiveHealing float64\n  Overhealing float64\n  EffectiveCritHealing float64",
  );
  metrics = replace(
    metrics,
    "\t\tHealing:                tam.Healing,",
    `\t\tHealing:                tam.Healing,
    EffectiveHealing: tam.EffectiveHealing,
    Overhealing: tam.Overhealing,
    EffectiveCritHealing: tam.EffectiveCritHealing,`,
  );
  metrics = replace(
    metrics,
    "\t\thps:     NewDistributionMetrics(),",
    "\t\thps:     NewDistributionMetrics(),\n" +
      distributions.map(([name]) => `    ${name}: NewDistributionMetrics(),`).join("\n"),
  );
  metrics = replace(
    metrics,
    "\t\ttam.Healing += spellTargetMetrics.TotalHealing",
    `\t\ttam.Healing += spellTargetMetrics.TotalHealing
    tam.EffectiveHealing += spellTargetMetrics.TotalEffectiveHealing
    tam.Overhealing += spellTargetMetrics.TotalOverhealing
    tam.EffectiveCritHealing += spellTargetMetrics.TotalEffectiveCritHealing`,
  );
  metrics = replace(
    metrics,
    "\t\t\tunitMetrics.hps.Total += spellTargetMetrics.TotalHealing + spellTargetMetrics.TotalAbsorbedShielding",
    `\t\t\tunitMetrics.hps.Total += spellTargetMetrics.TotalEffectiveHealing + spellTargetMetrics.TotalAbsorbedShielding
      unitMetrics.rawHealing.Total += spellTargetMetrics.TotalHealing
      unitMetrics.effectiveHealing.Total += spellTargetMetrics.TotalEffectiveHealing
      unitMetrics.overhealing.Total += spellTargetMetrics.TotalOverhealing
      unitMetrics.absorbedShielding.Total += spellTargetMetrics.TotalAbsorbedShielding`,
  );
  metrics = replace(
    metrics,
    "\tunitMetrics.dps.Total += petMetrics.dps.Total",
    "\tunitMetrics.dps.Total += petMetrics.dps.Total\n  unitMetrics.hps.Total += petMetrics.hps.Total\n" +
      distributions
        .map(([name]) => `  unitMetrics.${name}.Total += petMetrics.${name}.Total`)
        .join("\n"),
  );
  metrics = replace(
    metrics,
    "\tunitMetrics.hps.reset()",
    "\tunitMetrics.hps.reset()\n" +
      distributions.map(([name]) => `  unitMetrics.${name}.reset()`).join("\n"),
  );
  metrics = replace(
    metrics,
    "\tunitMetrics.hps.doneIteration(sim)",
    "\tunitMetrics.hps.doneIteration(sim)\n" +
      distributions.map(([name]) => `  unitMetrics.${name}.doneIteration(sim)`).join("\n"),
  );
  metrics = replace(
    metrics,
    "\t\tHps:           unitMetrics.hps.ToProto(),",
    "\t\tHps:           unitMetrics.hps.ToProto(),\n" +
      distributions
        .map(([name, field]) => `    ${field}: unitMetrics.${name}.ToProto(),`)
        .join("\n"),
  );

  let raid = replace(
    source.raid,
    "\thpsMetrics DistributionMetrics",
    "\thpsMetrics DistributionMetrics\n" +
      distributions.map(([name]) => `  ${name}Metrics DistributionMetrics`).join("\n"),
    2,
  );
  for (const receiver of ["party", "raid"]) {
    const constructor =
      receiver === "party"
        ? "\t\thpsMetrics: NewDistributionMetrics(),"
        : "\t\thpsMetrics:   NewDistributionMetrics(),";
    raid = replace(
      raid,
      constructor,
      constructor +
        "\n" +
        distributions.map(([name]) => `    ${name}Metrics: NewDistributionMetrics(),`).join("\n"),
    );
    raid = replace(
      raid,
      `\t${receiver}.hpsMetrics.reset()`,
      `\t${receiver}.hpsMetrics.reset()\n` +
        distributions.map(([name]) => `  ${receiver}.${name}Metrics.reset()`).join("\n"),
    );
    raid = replace(
      raid,
      `\t${receiver}.hpsMetrics.doneIteration(sim)`,
      `\t${receiver}.hpsMetrics.doneIteration(sim)\n` +
        distributions.map(([name]) => `  ${receiver}.${name}Metrics.doneIteration(sim)`).join("\n"),
    );
    raid = replace(
      raid,
      `\t\tHps: ${receiver}.hpsMetrics.ToProto(),`,
      `\t\tHps: ${receiver}.hpsMetrics.ToProto(),\n` +
        distributions
          .map(([name, field]) => `    ${field}: ${receiver}.${name}Metrics.ToProto(),`)
          .join("\n"),
    );
  }
  raid = replace(
    raid,
    "\t\tparty.hpsMetrics.Total += agent.GetCharacter().Metrics.hps.Total",
    "\t\tparty.hpsMetrics.Total += agent.GetCharacter().Metrics.hps.Total\n" +
      distributions
        .map(
          ([name]) =>
            `    party.${name}Metrics.Total += agent.GetCharacter().Metrics.${name}.Total`,
        )
        .join("\n"),
  );
  raid = replace(
    raid,
    "\t\traid.hpsMetrics.Total += party.hpsMetrics.Total",
    "\t\traid.hpsMetrics.Total += party.hpsMetrics.Total\n" +
      distributions
        .map(([name]) => `    raid.${name}Metrics.Total += party.${name}Metrics.Total`)
        .join("\n"),
  );

  let concurrent = source.concurrent;
  for (const line of [
    "\t\tHps:       rsrc.newDistMetrics(),",
    "\t\tHps:     rsrc.newDistMetrics(),",
    "\t\t\tHps:     rsrc.newDistMetrics(),",
  ])
    concurrent = replace(
      concurrent,
      "\n" + line,
      "\n" +
        line +
        "\n" +
        distributions.map(([, field]) => `    ${field}: rsrc.newDistMetrics(),`).join("\n"),
    );
  concurrent = replace(
    concurrent,
    "\t\tbaseTgt.Healing += addTgt.Healing",
    "\t\tbaseTgt.Healing += addTgt.Healing\n    baseTgt.EffectiveHealing += addTgt.EffectiveHealing\n    baseTgt.Overhealing += addTgt.Overhealing\n    baseTgt.EffectiveCritHealing += addTgt.EffectiveCritHealing",
  );
  for (const [base, add] of [
    ["base", "add"],
    ["baseParty", "party"],
    ["rsrc.Combined.RaidMetrics", "result.RaidMetrics"],
  ]) {
    const marker = `rsrc.combineDistMetrics(${base}.Hps, ${add}.Hps, isLast, weight)`;
    concurrent = replace(
      concurrent,
      marker,
      marker +
        "\n" +
        distributions
          .map(
            ([, field]) =>
              `  if ${add}.${field} != nil { rsrc.combineDistMetrics(${base}.${field}, ${add}.${field}, isLast, weight) }`,
          )
          .join("\n"),
    );
  }
  return { api, delivery, metrics, raid, concurrent };
}
