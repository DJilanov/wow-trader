import { mkdir, rename, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import {
  pairingPollResponseSchema,
  pairingStartResponseSchema,
  traderSyncResponseSchema,
  traderSyncSchema,
  type TraderSync,
  type TraderWatch,
} from "@wow-trader/contracts";

export function traderAccountBase(endpoint: URL): URL {
  if (
    ["helper.kfcguild.online", "kfcguild.online", "www.kfcguild.online"].includes(endpoint.hostname)
  )
    return new URL("https://kfcguild.online/tools/api/trader/");
  if (
    !["localhost", "127.0.0.1", "[::1]"].includes(endpoint.hostname) ||
    !["http:", "https:"].includes(endpoint.protocol)
  )
    throw new Error("Unsupported Trader account endpoint");
  return new URL("/tools/api/trader/", endpoint);
}
async function request(
  endpoint: URL,
  action: string,
  value: unknown,
  signal?: AbortSignal,
  credential?: string,
): Promise<unknown> {
  const response = await fetch(new URL(action, traderAccountBase(endpoint)), {
    method: "POST",
    headers: {
      "content-type": "application/json",
      ...(credential ? { authorization: `Bearer ${credential}` } : {}),
    },
    body: JSON.stringify(value),
    signal: AbortSignal.any([AbortSignal.timeout(20_000), ...(signal ? [signal] : [])]),
    redirect: "error",
  });
  if (response.status === 429)
    throw new Error("Account synchronization is rate limited. Retry after a short wait.");
  if (!response.ok)
    throw new Error(
      response.status === 401
        ? "Reconnect Companion to your Trader account."
        : `Trader account request failed (HTTP ${response.status}).`,
    );
  return response.json() as Promise<unknown>;
}
export async function startCompanionPairing(
  endpoint: URL,
  label: string,
  signal?: AbortSignal,
): Promise<ReturnType<typeof pairingStartResponseSchema.parse>> {
  const result = pairingStartResponseSchema.parse(
    await request(endpoint, "pairing/start", { label }, signal),
  );
  const target = new URL(result.verificationUri),
    trusted = traderAccountBase(endpoint);
  if (
    target.origin !== trusted.origin ||
    target.pathname !== "/tools/forever/trader/account" ||
    target.searchParams.get("code") !== result.userCode
  )
    throw new Error("Pairing returned an untrusted verification address");
  return result;
}
export async function pollCompanionPairing(
  endpoint: URL,
  deviceCode: string,
  signal?: AbortSignal,
): Promise<ReturnType<typeof pairingPollResponseSchema.parse>> {
  return pairingPollResponseSchema.parse(
    await request(endpoint, "pairing/poll", { deviceCode }, signal),
  );
}
export async function syncTraderAccount(
  endpoint: URL,
  credential: string,
  value: TraderSync,
  signal?: AbortSignal,
): Promise<ReturnType<typeof traderSyncResponseSchema.parse>> {
  return traderSyncResponseSchema.parse(
    await request(endpoint, "sync", traderSyncSchema.parse(value), signal, credential),
  );
}

export async function installTraderPreferences(
  root: string,
  watches: readonly TraderWatch[],
  acknowledgedTrades: readonly string[],
  acknowledgedChanges: readonly string[],
): Promise<void> {
  const quote = (value: string): string =>
    '"' +
    value
      .replaceAll("\\", "\\\\")
      .replaceAll('"', '\\"')
      .replaceAll("\r", "\\r")
      .replaceAll("\n", "\\n") +
    '"';
  const content = `-- Generated by WoW Trader Companion. Contains preferences, never credentials.\nWOW_TRADER_ACCOUNT_DATA = { schemaVersion=1, connected=true, generatedAt=${Math.floor(Date.now() / 1000)},
 watches={${watches.map((watch) => `{product=${quote(watch.product)},market=${quote(watch.market)},itemId=${watch.itemId},name=${quote(watch.name)},maximumBuyCopper=${watch.maximumBuyCopper ? quote(watch.maximumBuyCopper) : "nil"},minimumProfitCopper=${quote(watch.minimumProfitCopper)},maximumUnits=${watch.maximumUnits},cooldownMinutes=${watch.cooldownMinutes}}`).join(",")}},
 acknowledgedTrades={${acknowledgedTrades.map(quote).join(",")}},acknowledgedChanges={${acknowledgedChanges.map(quote).join(",")}} }\n`;
  const directory = path.join(root, "Interface", "AddOns", "WowTraderCollector");
  await mkdir(directory, { recursive: true });
  const temporary = path.join(directory, `.AccountData.${process.pid}.tmp`);
  try {
    await writeFile(temporary, content, { mode: 0o600 });
    await rename(temporary, path.join(directory, "AccountData.lua"));
  } finally {
    await rm(temporary, { force: true });
  }
}
